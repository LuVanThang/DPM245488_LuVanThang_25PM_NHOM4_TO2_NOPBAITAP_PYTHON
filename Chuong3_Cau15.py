'''
(a) range(5) -> Dãy số bắt đầu từ 0 và dừng trước 5
(b) range(5, 10) -> Dãy số bắt đầu từ 5 và dừng trước 10
(c) range(5, 20, 3) -> Bắt đầu từ 5, mỗi số cách nhau 3 đơn vị, dừng trước 20
(d) range(20, 5, -1) -> Bắt đầu từ 20, đếm lùi 1 đơn vị, dừng trước 5
(e) range(20, 5, -3) -> Bắt đầu từ 20, đếm lùi 3 đơn vị, dừng trước 5
(f) range(10, 5) -> Chương trình muốn đếm lùi(vì không có đơn vị đếm lùi) từ 10 để đến 5. Vì 10 đã lớn hơn 5, điều kiện không thỏa và báo lỗi
(g) range(0) -> Dẫy số rỗng không có giá trị
(h) range(10, 101, 10) -> Bắt đầu từ 10, tăng 10 đơn vị, dừng trước 101
(i) range(10, -1, -1) -> Bắt đầu từ 10, đếm lùi, dừng trước khi chạm -1
(j) range(-3, 4) -> Bắt đầu từ -3, đếm tiến, dừng trước 4
(k) range(0, 10, 1) -> Bắt đầu từ 0, đếm tiến, dừng trước 10
'''
