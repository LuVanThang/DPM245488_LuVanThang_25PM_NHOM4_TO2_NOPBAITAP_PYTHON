#Trình bày một số hàm quan trọng trong xử lý Chuỗi của Python
'''
strip([chars]) Dùng để xóa các ký tự trống ở đầu và cuối chuỗi
split(delimiter) Dùng để tách chuỗi thành các phần tử con dựa trên ký tự phân cách delimiter
join(list) Dùng để nối các phần tử trong một danh sách thành một chuỗi, với ký tự phân cách là ký tự gọi hàm join
find(sub) Dùng để tìm vị trí xuất hiện đầu tiên của chuỗi con sub trong chuỗi chính. Nếu không tìm thấy, hàm trả về -1
upper() Dùng để chuyển tất cả các ký tự trong chuỗi thành chữ in hoa
lower() Dùng để chuyển tất cả các ký tự trong chuỗi thành chữ thường
capitalize() Dùng để chuyển ký tự đầu tiên của chuỗi thành chữ in hoa
title() Dùng để chuyển ký tự đầu tiên của mỗi từ trong chuỗi thành chữ in hoa
replace(old, new) Dùng để thay thế tất cả các ký tự old trong chuỗi bằng ký tự new
isalpha() Dùng để kiểm tra xem tất cả các ký tự trong chuỗi có phải là chữ cái hay không
isdigit() Dùng để kiểm tra xem tất cả các ký tự trong chuỗi có phải là chữ số hay không
'''